// Writes the studies marked "synthetic" in data/studies.source.json as PS3.10 files, with no download.
// Every byte comes from the study's definition: UIDs are hashes of its names, and the images are
// computed phantoms, so a rebuild gives the same files. No person's images are in them.
//   bun scripts/generate-synthetic.ts [output directory]
import { mkdir, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";

const EVRLE = "1.2.840.10008.1.2.1";
const IMPLEMENTATION_UID = "2.25.206411918043771236429310561102839571521";
const SIZE = 256;
const COMMENT = "SYNTHETIC. Generated by scripts/generate-synthetic.ts. Not an image of any person.";

export interface SyntheticSeries { number: number; modality: string; sopClass: string; description: string; bodyPart: string; instances: number; }
export interface SyntheticStudy { id: string; site: string; synthetic: true; patient: { id: string; mrn: string; dicomName: string; birthDate: string; sex: string }; accession: string; studyDate: string; studyTime: string; description: string; series: SyntheticSeries[]; }

/** A UID under 2.25, the root for UIDs made from a 128-bit number. */
export const syntheticUid = (...names: (string | number)[]) => `2.25.${BigInt(`0x${createHash("sha256").update(names.join("/")).digest("hex").slice(0, 32)}`)}`;

type Element = [group: number, element: number, vr: string, value: string | Uint8Array];
const LONG_VRS = new Set(["OB", "OW"]);
const ascii = new TextEncoder();
/** PS3.5: a value has an even length, padded with a null for UI and a space for other text. */
function encode([group, element, vr, value]: Element): Uint8Array {
  const raw = typeof value === "string" ? ascii.encode(value.length % 2 ? `${value}${vr === "UI" ? "\0" : " "}` : value) : value;
  const long = LONG_VRS.has(vr);
  const out = new Uint8Array((long ? 12 : 8) + raw.length);
  const dv = new DataView(out.buffer);
  dv.setUint16(0, group, true); dv.setUint16(2, element, true);
  out.set(ascii.encode(vr), 4);
  if (long) dv.setUint32(8, raw.length, true); else dv.setUint16(6, raw.length, true);
  out.set(raw, long ? 12 : 8);
  return out;
}
const join8 = (parts: Uint8Array[]) => { const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0)); let at = 0; for (const p of parts) { out.set(p, at); at += p.length; } return out; };
const us = (v: number) => new Uint8Array(new Uint16Array([v]).buffer);

/** Nested ellipses that move with the series and the instance, in integer arithmetic. */
function phantom(series: number, instance: number, peak: number): Uint8Array {
  const pixels = new Uint16Array(SIZE * SIZE);
  const c = SIZE / 2, shift = (series * 7 + instance * 5) % 24 - 12;
  const shapes: [number, number, number, number, number][] = [
    [c, c, 110, 96 - instance * 2, Math.floor(peak * .22)],
    [c, c, 100, 86 - instance * 2, Math.floor(peak * .48)],
    [c - 34 + shift, c - 12, 24 + series * 2, 34, Math.floor(peak * .72)],
    [c + 36, c + 8 - shift, 20, 28 + series, Math.floor(peak * .3)],
    [c + shift, c + 44, 12, 8 + instance, peak],
  ];
  for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
    let v = (x + y) % 16;
    for (const [cx, cy, rx, ry, level] of shapes) if ((x - cx) ** 2 * ry ** 2 + (y - cy) ** 2 * rx ** 2 <= rx ** 2 * ry ** 2) v = level + ((x ^ y) & 7);
    pixels[y * SIZE + x] = v;
  }
  return new Uint8Array(pixels.buffer);
}

/** The attributes each image type requires, beyond what they all share. */
function byModality(s: SyntheticSeries, n: number, frame: string): Element[] {
  const spatial: Element[] = [[0x0018, 0x0050, "DS", "3"], [0x0020, 0x0032, "DS", `-128\\-128\\${n * 3}`], [0x0020, 0x0037, "DS", "1\\0\\0\\0\\1\\0"], [0x0020, 0x0052, "UI", frame], [0x0020, 0x1041, "DS", String(n * 3)], [0x0028, 0x0030, "DS", "1\\1"]];
  if (s.modality === "CT") return [[0x0008, 0x0008, "CS", "DERIVED\\PRIMARY\\AXIAL"], [0x0018, 0x0060, "DS", "120"], ...spatial, [0x0028, 0x1050, "DS", "400"], [0x0028, 0x1051, "DS", "2000"], [0x0028, 0x1052, "DS", "-1024"], [0x0028, 0x1053, "DS", "1"], [0x0028, 0x1054, "LO", "HU"]];
  if (s.modality === "MR") return [[0x0008, 0x0008, "CS", "DERIVED\\PRIMARY\\OTHER"], [0x0018, 0x0020, "CS", "SE"], [0x0018, 0x0021, "CS", "NONE"], [0x0018, 0x0022, "CS", "NONE"], [0x0018, 0x0023, "CS", "2D"], ...spatial.slice(0, 1), [0x0018, 0x0080, "DS", "500"], [0x0018, 0x0081, "DS", "15"], [0x0018, 0x0091, "IS", "1"], ...spatial.slice(1), [0x0028, 0x1050, "DS", "900"], [0x0028, 0x1051, "DS", "1800"]];
  if (s.modality === "CR") return [[0x0008, 0x0008, "CS", "DERIVED\\PRIMARY"], [0x0018, 0x1164, "DS", "1\\1"], [0x0020, 0x0020, "CS", "L\\F"], [0x0028, 0x1050, "DS", "2000"], [0x0028, 0x1051, "DS", "4000"]];
  return [[0x0008, 0x0008, "CS", "DERIVED\\SECONDARY"], [0x0008, 0x0064, "CS", "SYN"], [0x0020, 0x0020, "CS", "L\\F"], [0x0028, 0x1050, "DS", "2000"], [0x0028, 0x1051, "DS", "4000"]];
}

/** One instance, as a Part 10 file in Explicit VR Little Endian. */
export function syntheticInstance(study: SyntheticStudy, s: SyntheticSeries, n: number): Uint8Array {
  const sop = syntheticUid(study.id, s.number, n);
  const date = study.studyDate.replaceAll("-", ""), time = study.studyTime.replaceAll(":", "");
  const peak = s.modality === "CR" || s.modality === "SM" ? 4000 : 1800;
  const data: Element[] = [
    [0x0008, 0x0016, "UI", s.sopClass], [0x0008, 0x0018, "UI", sop], [0x0008, 0x0020, "DA", date], [0x0008, 0x0023, "DA", date], [0x0008, 0x0030, "TM", time], [0x0008, 0x0033, "TM", time],
    [0x0008, 0x0050, "SH", study.accession], [0x0008, 0x0060, "CS", s.modality], [0x0008, 0x0070, "LO", "SYNTHETIC: SMART Imaging proxy demo"], [0x0008, 0x0090, "PN", ""], [0x0008, 0x1030, "LO", study.description], [0x0008, 0x103e, "LO", s.description],
    [0x0010, 0x0010, "PN", study.patient.dicomName], [0x0010, 0x0020, "LO", study.patient.mrn], [0x0010, 0x0030, "DA", study.patient.birthDate.replaceAll("-", "")], [0x0010, 0x0040, "CS", study.patient.sex],
    [0x0018, 0x0015, "CS", s.bodyPart], [0x0020, 0x000d, "UI", syntheticUid(study.id)], [0x0020, 0x000e, "UI", syntheticUid(study.id, s.number)], [0x0020, 0x0010, "SH", study.accession.slice(0, 16)], [0x0020, 0x0011, "IS", String(s.number)], [0x0020, 0x0013, "IS", String(n)], [0x0020, 0x4000, "LT", COMMENT],
    [0x0028, 0x0002, "US", us(1)], [0x0028, 0x0004, "CS", "MONOCHROME2"], [0x0028, 0x0010, "US", us(SIZE)], [0x0028, 0x0011, "US", us(SIZE)], [0x0028, 0x0100, "US", us(16)], [0x0028, 0x0101, "US", us(16)], [0x0028, 0x0102, "US", us(15)], [0x0028, 0x0103, "US", us(0)],
    ...byModality(s, n, syntheticUid(study.id, s.number, "frame")),
    [0x7fe0, 0x0010, "OW", phantom(s.number, n, peak)],
  ];
  data.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const meta = join8(([[0x0002, 0x0001, "OB", new Uint8Array([0, 1])], [0x0002, 0x0002, "UI", s.sopClass], [0x0002, 0x0003, "UI", sop], [0x0002, 0x0010, "UI", EVRLE], [0x0002, 0x0012, "UI", IMPLEMENTATION_UID], [0x0002, 0x0013, "SH", "SYNTHETIC_DEMO"]] as Element[]).map(encode));
  const group = new Uint8Array(new Uint32Array([meta.length]).buffer);
  return join8([new Uint8Array(128), ascii.encode("DICM"), encode([0x0002, 0x0000, "UL", group]), meta, ...data.map(encode)]);
}

/** Writes each study's files under `dir`, in a directory named for the study, replacing what was there. */
export async function writeSynthetic(dir: string, studies: SyntheticStudy[]) {
  for (const study of studies) {
    const at = join(dir, study.id);
    await rm(at, { recursive: true, force: true });
    await mkdir(at, { recursive: true });
    for (const s of study.series) for (let n = 1; n <= s.instances; n++) await Bun.write(join(at, `series-${s.number}-${n}.dcm`), syntheticInstance(study, s, n));
  }
}
export const syntheticStudies = (def: { studies: any[] }): SyntheticStudy[] => def.studies.filter(s => s.synthetic);

if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  const dir = process.argv[2] ?? join(process.env.SOURCES_DIR || join(root, "data/sources"), "synthetic");
  const studies = syntheticStudies(await Bun.file(join(root, "data/studies.source.json")).json());
  await writeSynthetic(dir, studies);
  console.log(`${dir}: ${studies.length} synthetic studies, ${studies.reduce((n, st) => n + st.series.reduce((m, s) => m + s.instances, 0), 0)} instances`);
}
